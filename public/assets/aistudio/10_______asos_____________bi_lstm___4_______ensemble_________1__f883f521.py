"""### [5단계] 여행 맞춤형 기간 가변 데이터 파이프라인 & 추론 서비스 엔진
여행객의 예약 정보(출발일, 기간)에 맞춰 단기/중기/장기 예측을 동적으로 처리할 수 있도록 타임스탬프 슬라이서와 전용 데이터 로더를 구축합니다.
"""

import pandas as pd
from torch.utils.data import Dataset, DataLoader

class TravelerWeatherDataset(Dataset):
    """
    [여행 기간 맞춤형 타임스탬프 슬라이싱 데이터셋]
    - 여행객이 입력한 여행 기간(Duration)에 맞춰 적응형(Adaptive) 기상 입력창을 결정하고
      과거 10개년 기상 데이터에서 학습 세트를 동적으로 구성합니다.
    """
    def __init__(self, historical_df, target_cols, feature_cols, max_len=365):
        """
        :param historical_df: 기상청 10개년 ASOS 데이터가 들어있는 pandas DataFrame (index: Datetime)
        :param target_cols: 예측 목표 변수 리스트 (최저, 최고, 평균기온, 강수확률 등)
        :param feature_cols: 학습 입력 피처 리스트 (7대 관측값)
        """
        self.df = historical_df.sort_index()
        self.target_cols = target_cols
        self.feature_cols = feature_cols
        self.max_len = max_len

    def slice_by_travel_plan(self, start_date, duration):
        """
        여행객이 지정한 출발일(start_date)과 여행 기간(duration)에 맞춰
        단기/중기/장기 모델 입력 시퀀스를 최적화된 Timestamp 크기로 슬라이싱합니다.
        """
        start_dt = pd.to_datetime(start_date)

        # 1. 여행 기간에 따른 과거 기상 분석 창(Lookback Window) 동적 정의
        if duration <= 3:      # 단기 여행 (최근 단기 변동 집중)
            lookback_days = 14
            service_type = "단기 안심 기상 서비스 (Short-Term)"
        elif duration <= 7:    # 중기 여행
            lookback_days = 45
            service_type = "중기 맞춤 일정 플래너 (Mid-Term)"
        else:                  # 장기 여행 (계절성 장기 추세 분석)
            lookback_days = 120
            service_type = "장기 안심 기후 추론 (Long-Term)"

        # 2. 타임스탬프 기준 인덱싱
        history_start = start_dt - pd.Timedelta(days=lookback_days)
        history_end = start_dt - pd.Timedelta(days=1)

        # 3. 데이터 자르기
        x_slice = self.df.loc[history_start:history_end][self.feature_cols]

        # 4. 신경망 입력 차원 맞춤용 패딩(Padding) 혹은 트리밍
        features = x_slice.values
        if len(features) < self.max_len:
            # 부족한 부분은 과거 평균값이나 제로 패딩으로 채움 (여기선 전방 제로 패딩)
            pad_width = self.max_len - len(features)
            features = np.pad(features, ((pad_width, 0), (0, 0)), mode='constant')
        else:
            features = features[-self.max_len:]

        return torch.tensor(features, dtype=torch.float32), service_type

