"""### [7단계] 계절별 종합 기상 현상(맑음/구름/강수/바람) 추론 엔진
기온 데이터에 더해 강수량, 습도, 풍속 등을 종합 분석하여 여행자 맞춤형 기상 현상 판정 결과를 제공합니다.
"""

class SeasonalWeatherRuleEngine:
    """
    [계절 맞춤형 종합 기상 판정 엔진]
    - 기온 외에 강수량, 습도, 풍속 데이터를 종합하여 여행객이 직관적으로 이해할 수 있는 날씨 메인 현상을 판정합니다.
    """
    @staticmethod
    def get_season(date):
        month = pd.to_datetime(date).month
        if month in [3, 4, 5]:
            return "봄 (Spring)"
        elif month in [6, 7, 8]:
            return "여름 (Summer)"
        elif month in [9, 10, 11]:
            return "가을 (Autumn)"
        else:
            return "겨울 (Winter)"

    @staticmethod
    def diagnose_phenomenon(temp, rainfall_val, humidity, wind_speed, season):
        # 1. 강수 판정 (비 또는 눈)
        if rainfall_val > 5.0:
            if "겨울" in season and temp < 2.0:
                status = "눈 온 후 흐림 ❄️"
            else:
                status = "비/소나기 🌧️"
        # 2. 바람 판정
        elif wind_speed > 8.0:
            status = "강풍 주의 💨"
        # 3. 구름 및 습도 기준 판정
        elif humidity > 75.0:
            status = "흐리고 구름많음 ☁️"
        elif humidity > 50.0:
            status = "대체로 맑음 ⛅"
        else:
            status = "매우 맑음 ☀️"

        # 4. 계절별 주의 가이드 결합
        guide = ""
        if "봄" in season:
            guide = "꽃샘추위 혹은 황사/미세먼지를 대비해 마스크를 준비하세요!"
            if wind_speed > 5.0: guide += " (바람 다소 강함)"
        elif "여름" in season:
            if temp > 30.0:
                guide = "폭염 경보! 자외선 차단제와 충분한 수분 섭취가 필수입니다."
            else:
                guide = "덥고 습한 전형적인 여름 날씨입니다. 휴대용 우산을 챙기세요."
        elif "가을" in season:
            guide = "큰 일교차에 대비해 가벼운 아우터(바람막이)를 준비하시면 좋습니다."
        elif "겨울" in season:
            guide = "강추위 대비 두꺼운 패딩과 핫팩을 챙기시고 안전 운전에 유의하세요."

        return status, guide

